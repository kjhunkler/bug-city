export function drawJar(ctx) {
  const r = (x, y, w, h, c) => {
    ctx.fillStyle = c;
    ctx.fillRect(x, y, w, h);
  };
  r(4, 1, 10, 3, "#5d6049");
  r(5, 2, 8, 1, "#c68d54");
  r(5, 4, 8, 2, "#789481");
  r(3, 6, 12, 11, "#486757");
  r(5, 17, 8, 1, "#486757");
  r(4, 7, 10, 9, "#cce4bc");
  r(5, 8, 1, 5, "#ffffd6");
  r(8, 10, 5, 4, "#dc744c");
  r(9, 9, 3, 1, "#675741");
  r(10, 11, 1, 2, "#5b513b");
}
